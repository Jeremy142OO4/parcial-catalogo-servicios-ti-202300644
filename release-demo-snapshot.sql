SELECT jsonb_build_object(
 'level1',(SELECT count(*) FROM services_level1),
 'level2',(SELECT count(*) FROM services_level2),
 'queues',(SELECT count(*) FROM queues),
 'tickets',(SELECT count(*) FROM tickets),
 'devices',(SELECT count(*) FROM configuration_items WHERE is_device AND is_active),
 'ticket_digest',(SELECT md5(string_agg(row_to_json(t)::text,'' ORDER BY id)) FROM tickets t),
 'history_digest',(SELECT md5(string_agg(row_to_json(t)::text,'' ORDER BY id)) FROM ticket_history t),
 'ci_digest',(SELECT md5(string_agg(row_to_json(t)::text,'' ORDER BY id)) FROM configuration_items t),
 'level1_digest',(SELECT md5(string_agg(row_to_json(t)::text,'' ORDER BY id)) FROM services_level1 t),
 'level2_digest',(SELECT md5(string_agg(row_to_json(t)::text,'' ORDER BY id)) FROM services_level2 t),
 'user_digest',(SELECT md5(string_agg(row_to_json(t)::text,'' ORDER BY id)) FROM app_users t),
 'role_digest',(SELECT md5(string_agg(row_to_json(t)::text,'' ORDER BY user_id,role_code)) FROM user_roles t),
 'queue_digest',(SELECT md5(string_agg(row_to_json(t)::text,'' ORDER BY id)) FROM queues t),
 'grant_digest',(SELECT md5(string_agg(row_to_json(t)::text,'' ORDER BY id)) FROM queue_grants t),
 'class_digest',(SELECT md5(string_agg((to_jsonb(t)-'technical_profile')::text,'' ORDER BY id)) FROM ci_classes t),
 'relations_digest',(SELECT md5(string_agg(row_to_json(t)::text,'' ORDER BY id)) FROM ci_relations t),
 'faq_digest',(SELECT md5(string_agg(row_to_json(t)::text,'' ORDER BY id)) FROM faq_articles t),
 'attachments_digest',(SELECT md5(string_agg(row_to_json(t)::text,'' ORDER BY id)) FROM ticket_attachments t));
